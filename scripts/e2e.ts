/**
 * End-to-end check: generates a project, installs it and runs its own checks
 * (lint with zero warnings, stylelint, typecheck, tests, production build).
 *
 *   node scripts/e2e.ts [--preset all|minimal|default|auth,legal] [--pm pnpm|npm|bun] [--supabase remote|local] [--skip-build]
 *
 * Projects are written to `.e2e/<preset>-<pm>` (gitignored) and kept for
 * inspection. Requires a prior `npm run build` only for the CLI smoke test in
 * CI; this script imports the generator from source.
 */
import { spawnSync } from "node:child_process";
import { appendFileSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { parseArgs } from "node:util";

import { getPmCommands } from "../src/generator/options.ts";
import { planProject } from "../src/generator/plan.ts";
import { writeProject } from "../src/generator/write.ts";
import { registry } from "../src/modules/registry.ts";
import { resolveModules } from "../src/modules/resolve.ts";
import { MODULE_IDS, PACKAGE_MANAGERS } from "../src/modules/types.ts";

import type { ModuleId, PackageManager, SupabaseTarget } from "../src/modules/types.ts";

const { values } = parseArgs({
  options: {
    preset: { type: "string", default: "all" },
    pm: { type: "string", default: "pnpm" },
    "skip-build": { type: "boolean", default: false },
    supabase: { type: "string", default: "remote" },
  },
});

const preset = values.preset;
const pm = values.pm as PackageManager;

if (!PACKAGE_MANAGERS.includes(pm)) {
  throw new Error(`Unknown package manager "${pm}".`);
}

function selection(value: string): ModuleId[] {
  if (value === "all") {
    return [...MODULE_IDS];
  }

  if (value === "minimal") {
    return [];
  }

  if (value === "default") {
    return MODULE_IDS.filter((id) => registry[id].default);
  }

  return value.split(",").map((id) => id.trim()) as ModuleId[];
}

const { enabled } = resolveModules(selection(preset), registry);
const directory = resolve(".e2e", `${preset.replaceAll(",", "+")}-${pm}-${values.supabase}`);

rmSync(directory, { recursive: true, force: true });
writeProject(
  planProject({
    name: "E2E App",
    slug: "e2e-app",
    description: "Generated by the create-next-stack end-to-end check.",
    pm,
    supabaseTarget: values.supabase as SupabaseTarget,
    port: 3000,
    modules: enabled,
  }),
  directory,
);

console.log(`\nGenerated ${directory} with: ${enabled.join(", ")}\n`);

// Escape hatch for machines whose security policy blocks a freshly released
// native binary: E2E_OVERRIDES='{"@swc/core":"1.16.2"}' pins it in the
// generated project only (pnpm-workspace.yaml for pnpm, package.json otherwise).
if (process.env.E2E_OVERRIDES) {
  const overrides = JSON.parse(process.env.E2E_OVERRIDES) as Record<string, string>;

  if (pm === "pnpm") {
    const lines = Object.entries(overrides).map(([name, version]) => `  '${name}': ${version}`);
    appendFileSync(join(directory, "pnpm-workspace.yaml"), `overrides:\n${lines.join("\n")}\n`);
  } else {
    const packageJsonPath = join(directory, "package.json");
    const packageJson = JSON.parse(readFileSync(packageJsonPath, "utf8")) as Record<string, unknown>;
    writeFileSync(packageJsonPath, `${JSON.stringify({ ...packageJson, overrides }, null, 2)}\n`);
  }
}

// Placeholder values so the production build can evaluate config modules.
const env = {
  ...process.env,
  CI: "true",
  NEXT_TELEMETRY_DISABLED: "1",
  NEXT_PUBLIC_SITE_URL: "http://localhost:3000",
  NEXT_PUBLIC_SUPABASE_URL: "http://127.0.0.1:54321",
  NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY: "e2e-placeholder",
};

function run(label: string, command: string) {
  console.log(`\n▶ ${label}: ${command}`);
  const started = Date.now();
  const result = spawnSync(command, { cwd: directory, env, shell: true, stdio: "inherit" });

  if (result.status !== 0) {
    console.error(`\n✖ ${label} failed (exit ${result.status ?? "signal"}).`);
    process.exit(result.status ?? 1);
  }

  console.log(`✔ ${label} (${((Date.now() - started) / 1000).toFixed(1)}s)`);
}

const commands = getPmCommands(pm);

run("git init", "git init -q");
run("install", commands.install);
run("lint", `${commands.exec} eslint --max-warnings 0`);
run("lint:styles", `${commands.run} lint:styles`);
run("typecheck", `${commands.run} typecheck`);
run("test", `${commands.run} test`);

if (!values["skip-build"]) {
  run("build", `${commands.run} build`);
}

console.log(`\nAll checks passed for ${join(".e2e", `${preset}-${pm}`)}.`);
