/**
 * Development helper: generates a project without prompts or installs.
 *
 *   node scripts/generate.ts <dir> [all|minimal|default|auth,legal,...] [pnpm|npm|bun]
 */
import { resolve } from "node:path";

import { planProject } from "../src/generator/plan.ts";
import { writeProject } from "../src/generator/write.ts";
import { registry } from "../src/modules/registry.ts";
import { resolveModules } from "../src/modules/resolve.ts";
import { MODULE_IDS } from "../src/modules/types.ts";

import type { ModuleId, PackageManager } from "../src/modules/types.ts";

const [directory, preset = "all", pm = "pnpm"] = process.argv.slice(2);

if (!directory) {
  console.error("Usage: node scripts/generate.ts <dir> [all|minimal|default|a,b] [pnpm|npm|bun]");
  process.exit(1);
}

function selection(value: string): ModuleId[] {
  if (value === "all") {
    return [...MODULE_IDS];
  }

  if (value === "minimal") {
    return [];
  }

  if (value === "default") {
    return MODULE_IDS.filter((id) => registry[id].default);
  }

  return value.split(",") as ModuleId[];
}

const { enabled } = resolveModules(selection(preset), registry);
const files = planProject({
  name: "Demo App",
  slug: "demo-app",
  description: "A demo project generated by create-next-stack.",
  pm: pm as PackageManager,
  port: 3000,
  modules: enabled,
});

writeProject(files, resolve(directory));
console.log(`Wrote ${files.length} files (${enabled.join(", ")}) to ${resolve(directory)}`);
